@pytest.mark.parametrize("failure,reason", [("rejected", "unsafe_state"), ("query", "command_failed"), ("cancelled", "command_failed")])
def test_candidate_validation_failure_restores_exact_hba_after_command_cleanup(native, failure, reason, monkeypatch):
    from taskman_ops.host_helper.commands import CommandCancelled
    files, commands, _ = native
    original = b"# original private policy\nlocal all all peer\n"
    files["destination"].write_bytes(original)
    files["destination"].chmod(0o604)
    original_metadata = metadata(files["destination"])
    files["config_file"].write_text("listen_addresses = '127.0.0.1'\n")
    commands.settings["password_encryption"] = "md5"
    event = Event()
    cleaned = []
    replace = os.replace

    def parser(count):
        if count == 1:
            return ""
        assert files["destination"].read_bytes() == files["stage"].read_bytes()
        assert backup(files).stat().st_mode & 0o777 == 0o700
        assert metadata(backup(files) / "pg_hba.conf")[2] == 0o600
        assert metadata(backup(files) / "metadata")[2] == 0o600
        assert (backup(files) / "metadata").read_text() == "%d:%d:%o\n" % original_metadata
        cleaned.append("command workers joined")
        if failure == "rejected":
            return "bad HBA"
        if failure == "cancelled":
            event.set()
            raise CommandCancelled("command cancelled")
        raise CommandError("private query diagnostics")

    def replace_after_cleanup(source, destination):
        if Path(source).read_bytes() == original:
            assert cleaned == ["command workers joined"]
        return replace(source, destination)

    commands.parser = parser
    monkeypatch.setattr(capability.os, "replace", replace_after_cleanup)
    with pytest.raises(capability.PostgreSQLConfigurationError) as caught:
        invoke(native, event=event)
    assert (caught.value.reason, caught.value.mutation_state, caught.value.manual) == (reason, "changed", False)
    assert files["destination"].read_bytes() == original
    assert metadata(files["destination"]) == original_metadata
    assert commands.settings["password_encryption"] == "scram-sha-256"
    assert not backup(files).exists()
    assert not list(files["destination"].parent.glob("*.taskman.*"))
    assert not any(argv[-1] == "restart" for argv, _ in commands.calls)


def test_restoration_failure_takes_precedence_and_retains_evidence(native, monkeypatch):
    files, commands, _ = native
    files["destination"].write_bytes(b"original HBA\n")
    replace = os.replace

    def fail_restoration(source, destination):
        if Path(source).read_bytes() == b"original HBA\n":
            raise OSError("private restoration failure")
        return replace(source, destination)

    monkeypatch.setattr(capability.os, "replace", fail_restoration)
    commands.parser = lambda count: "" if count == 1 else "invalid candidate"
    assert_error(native, "recovery_required", "changed", manual=True)
    assert (backup(files) / "pg_hba.conf").read_bytes() == b"original HBA\n"
    assert files["destination"].read_bytes() == files["stage"].read_bytes()
    assert not list(files["destination"].parent.glob("*.taskman.*"))


