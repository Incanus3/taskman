def test_inspection_honors_cancellation_after_final_native_command(native):
    _, commands, _ = native
    event = Event()
    def cancel_after_last(argv, kwargs):
        if "-C" in argv and argv[-1] == "password_encryption":
            event.set()
    commands.before = cancel_after_last
    with pytest.raises(capability.PostgreSQLConfigurationError) as caught:
        invoke(native, inspection=True, event=event)
    assert (caught.value.reason, caught.value.mutation_state) == ("command_failed", "unchanged")


def test_inspection_stops_when_command_quiescence_is_unproven(native):
    from taskman_ops.host_helper.commands import CommandCleanupError
    files, commands, _ = native
    original = files["destination"].read_bytes()
    def incomplete_cleanup(argv, kwargs):
        raise CommandCleanupError("cleanup failed")
    commands.before = incomplete_cleanup
    with pytest.raises(capability.PostgreSQLConfigurationError) as caught:
        invoke(native, inspection=True)
    assert (caught.value.reason, caught.value.mutation_state, caught.value.manual) == ("recovery_required", "unchanged", True)
    assert len(commands.calls) == 1
    assert files["destination"].read_bytes() == original
    assert not backup(files).exists()
