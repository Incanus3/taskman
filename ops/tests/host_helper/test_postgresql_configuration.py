def invoke(native, *, inspection=False, event=None):
    _, _, parameters = native
    function = capability.inspect_configuration if inspection else capability.configure_cluster
    return function(parameters, deadline=600.0, cancellation=Event() if event is None else event)


def backup(files):
    return files["destination"].with_name("pg_hba.conf.taskman-backup")


def metadata(path):
    state = path.stat()
    return state.st_uid, state.st_gid, state.st_mode & 0o7777


def assert_error(native, reason, mutation="unchanged", *, manual=False):
    with pytest.raises(capability.PostgreSQLConfigurationError) as caught:
        invoke(native)
    assert (caught.value.reason, caught.value.mutation_state, caught.value.manual) == (reason, mutation, manual)
    assert str(caught.value) == reason


def test_exact_configuration_is_read_only_and_unchanged(native):
    files, commands, _ = native
    before = {path: (path.read_bytes(), metadata(path), path.stat().st_mtime_ns)
              for path in (files["config_file"], files["destination"])}
    assert invoke(native, inspection=True) is False
    assert invoke(native) is False
    assert all((path.read_bytes(), metadata(path), path.stat().st_mtime_ns) == value for path, value in before.items())
    assert not backup(files).exists()
    assert not any("set" in argv or "restart" in argv for argv, _ in commands.calls)
    identities = [argv for argv, _ in commands.calls if argv[-1] == IDENTITY_SQL]
    assert len(identities) >= 3


